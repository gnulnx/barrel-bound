export const levels = configs.map((level, index) => {
  const rows = Array.from({ length: level.ladders.length + 1 }, (_, i) => {
    const tilt = (i % 2 === 0 ? 1 : -1) * level.slope * Math.sign(level.ladders[0])
    return {
      left: -level.half + (i % 2) * 0.72,
      right: level.half - ((i + 1) % 2) * 0.68,
      y: i * level.height,
      tilt,
    }
  })
  const entrySign = Math.sign(level.ladders[0])
  const goalX = -Math.sign(level.ladders.at(-1)) * (level.half - 1.25)
  const coinSpots = rows.flatMap((_, i) => [
    { row: i, x: i % 2 ? -0.9 : 1.8, offset: 0.77 },
    { row: i, x: i % 2 ? -3.2 : 4.25, offset: 1.45 },
  ])
  const routes = level.ladders.map((x, row) => [
    x,
    ...(level.sideLadders ?? []).filter(([i]) => i === row).map(([, side]) => side),
  ])
  const backdrop = level.sideLadders ? level.art : level.art + '-valley'
  return {
    ...level,
    index,
    rows,
    routes,
    backdrop,
    coinSpots,
    goalX,
    spawnX: -entrySign * (level.half - 1.55),
  }
})
export const floorAt = (row, x) => row.y + row.tilt * x
export const pad = (number, n = 2) => String(number).padStart(n, '0')
